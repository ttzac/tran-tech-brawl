// The work queue. Reads codex/manifest.json + codex/approvals.json and looks at what already exists in art-raw/.
//   node codex/next.mjs            next 10 images to generate (in plan order)
//   node codex/next.mjs 25         next 25
//   node codex/next.mjs --status   progress per group + what is waiting for approval (also writes codex/PROGRESS.md)
// Rules baked in: design sheets (tier 0) are generated for everyone up front; a hero/boss/minion's gameplay images
// (tier 1+) only unlock once its group is `true` in codex/approvals.json; everything else is never gated.
import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = JSON.parse(readFileSync(`${root}codex/manifest.json`, 'utf8'));
const approvals = JSON.parse(readFileSync(`${root}codex/approvals.json`, 'utf8'));
const have = (p) => existsSync(root + p);

const ORDER = [
  'heroes/zac', 'heroes/chain', 'heroes/aiden', 'heroes/david', 'heroes/annemaree', 'heroes/bec', 'heroes/caleb', 'heroes/cameron', 'heroes/jared', 'heroes/lachlan', 'heroes/ryan',
  'bosses/altwave', 'bosses/muskbot', 'minions/chatbot', 'minions/neurobot',
  'fx/global', 'stages/serverroom', 'stages/rooftop', 'items/icons', 'ui/ui', 'stages/promptfactory', 'stages/ramvault',
];
const groupOf = (m) => `${m.category}/${m.group}`;
const gated = (m) => ['heroes', 'bosses', 'minions'].includes(m.category);
const unlocked = (m) => m.tier === 0 || !gated(m) || approvals[groupOf(m)] === true;

// Parallel safety: a gameplay frame is only queued once the images it is matched against exist, so every batch is independent.
// idle_1 is the scale anchor for the whole character; the key pose of an animation anchors its in-betweens.
const ANCHOR = {
  run_2: 'run_1', run_3: 'run_1', run_4: 'run_1', run_5: 'run_1', run_6: 'run_1',
  melee_1: 'melee_3', melee_2: 'melee_3', melee_4: 'melee_3', special_1: 'special_2', special_3: 'special_2', hurt_2: 'hurt_1',
  melee2_1: 'melee2_3', melee2_2: 'melee2_3', melee2_4: 'melee2_3', special_5: 'special_2',
  ultimate_1: 'ultimate_4', ultimate_2: 'ultimate_4', ultimate_3: 'ultimate_4', ultimate_5: 'ultimate_4', ultimate_6: 'ultimate_4',
  respawn_2: 'respawn_1', respawn_3: 'respawn_1', taunt_2: 'taunt_1', victory_2: 'victory_1', victory_3: 'victory_1',
};
const isBody = (m) => ['heroes', 'bosses', 'minions'].includes(m.category) && m.kind !== 'fx' && !/^(sheet|portrait|icon|keyart)/.test(m.name);
const anchorOf = (m) => (!isBody(m) || m.name === 'idle_1' ? null : ANCHOR[m.name] ?? 'idle_1');
const anchorPath = (m) => { const a = anchorOf(m); return a ? `art-raw/${m.category}/${m.group}/${a}.png` : null; };
const rank = (m) => [m.tier, ORDER.indexOf(groupOf(m))];
const idx = new Map(manifest.map((m, i) => [m.id, i]));
const queue = manifest
  .filter((m) => unlocked(m) && !have(m.out) && (!anchorPath(m) || have(anchorPath(m))))
  .sort((a, b) => { const [ta, ga] = rank(a), [tb, gb] = rank(b); return ta - tb || ga - gb || idx.get(a.id) - idx.get(b.id); });

// images flagged by the validator (tools/art/check-raw.mjs writes codex/REVIEW.md)
const redo = existsSync(`${root}codex/REVIEW.md`)
  ? [...readFileSync(`${root}codex/REVIEW.md`, 'utf8').matchAll(/^- \[ \] `([^`]+)`: (.*)$/gm)].map((m) => ({ out: m[1], why: m[2] }))
  : [];

const show = (m) => {
  const refs = (m.refs ?? []).map((r) => r.replace(/ \(.*\)$/, '')).filter((r) => have(r));
  return `${m.id}\n    save as : ${m.out}\n    prompt  : codex/${m.prompt}\n    attach  : ${refs.join(' , ')}`;
};

const arg = process.argv[2];
if (arg === '--status') {
  const groups = {};
  for (const m of manifest) { const g = (groups[groupOf(m)] ??= { total: 0, done: 0, t1: 0, t1done: 0, sheets: 0, sheetsDone: 0 }); g.total++; if (have(m.out)) g.done++; if (m.tier === 1) { g.t1++; if (have(m.out)) g.t1done++; } if (m.tier === 0) { g.sheets++; if (have(m.out)) g.sheetsDone++; } }
  let md = `# PROGRESS (generated by \`node codex/next.mjs --status\`)\n\n| Group | Gate | Sheets | Tier 1 | All |\n|---|---|---|---|---|\n`;
  const waiting = [];
  for (const g of ORDER) {
    const s = groups[g]; if (!s) continue;
    const isGated = ['heroes', 'bosses', 'minions'].includes(g.split('/')[0]);
    const ok = approvals[g] === true;
    const gate = !isGated ? 'open' : ok ? 'approved' : s.sheetsDone === s.sheets ? 'WAITING FOR APPROVAL' : 'sheets not made yet';
    if (gate === 'WAITING FOR APPROVAL') waiting.push(g);
    md += `| ${g} | ${gate} | ${s.sheetsDone}/${s.sheets} | ${s.t1done}/${s.t1} | ${s.done}/${s.total} |\n`;
  }
  md += `\nQueue left: ${queue.length} images available now. Validator problems to redo: ${redo.length}.\n`;
  if (waiting.length) md += `\nWaiting for the user to approve the design sheets of: ${waiting.join(', ')}\n`;
  writeFileSync(`${root}codex/PROGRESS.md`, md);
  console.log(md);
} else {
  const n = Number(arg) || 10;
  if (redo.length) {
    console.log(`REDO FIRST (${redo.length} flagged by the validator):`);
    for (const r of redo.slice(0, n)) console.log(`  ${r.out}: ${r.why}`);
    console.log('');
  }
  if (!queue.length) {
    console.log('QUEUE EMPTY: nothing available right now. Run `node codex/next.mjs --status`, tell the user which design sheets are waiting for approval (codex/approvals.json), and stop.');
  } else {
    console.log(`NEXT ${Math.min(n, queue.length)} of ${queue.length} remaining (tier ${queue[0].tier}):\n`);
    queue.slice(0, n).forEach((m, i) => console.log(`${i + 1}. ${show(m)}\n`));
  }
}
