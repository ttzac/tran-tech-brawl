// Validates Codex's raw art against codex/manifest.json.
//   node tools/art/check-raw.mjs                 summary per group (missing / bad / ok)
//   node tools/art/check-raw.mjs heroes/zac      details for one group (add --tier 1 to limit)
// Checks: file exists, is a PNG/WebP image, roughly the expected size, flat magenta (or green) background on the
// corners, no magenta inside the subject (key-colour bleed), subject not touching the edge, feet near y=960 for body frames.
import sharp from 'sharp';
import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const manifest = JSON.parse(readFileSync(`${root}codex/manifest.json`, 'utf8'));
const args = process.argv.slice(2);
const group = args.find((a) => !a.startsWith('--'));
const tierArg = args.indexOf('--tier') >= 0 ? Number(args[args.indexOf('--tier') + 1]) : null;
const KEY_GREEN = (m) => m.group === 'ramvault';

const BODY = (m) => m.kind !== 'fx' && /^(heroes|bosses|minions)$/.test(m.category) && !/^(sheet|portrait|keyart|icon)/.test(m.name);

async function check(m) {
  const path = root + m.out;
  if (!existsSync(path)) return { status: 'missing' };
  const problems = [];
  const { data, info } = await sharp(path).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  const px = (x, y) => [data[(y * w + x) * 4], data[(y * w + x) * 4 + 1], data[(y * w + x) * 4 + 2]];
  const key = KEY_GREEN(m) ? [0, 255, 0] : [255, 0, 255];
  const isKey = ([r, g, b], t = 70) => Math.abs(r - key[0]) < t && Math.abs(g - key[1]) < t && Math.abs(b - key[2]) < t;
  const needsKey = !['stages', 'ui'].includes(m.category) || /^(plat_|prop_|logo_|hud_|menu_|touch|cursor)/.test(m.name);
  if (BODY(m) || m.kind === 'fx' || m.category === 'items') {
    if (w !== h) problems.push(`not square (${w}x${h})`);
    if (w < 512) problems.push(`too small (${w}px)`);
  }
  if (needsKey && !(m.category === 'stages' && /^(bg_far|preview)$/.test(m.name))) {
    const corners = [px(2, 2), px(w - 3, 2), px(2, h - 3), px(w - 3, h - 3)];
    if (corners.some((c) => !isKey(c))) problems.push(`background is not flat ${KEY_GREEN(m) ? 'green' : 'magenta'}`);
  }
  if (BODY(m) || m.kind === 'fx') {
    // subject bbox + key bleed
    let x0 = w, y0 = h, x1 = -1, y1 = -1, bleed = 0;
    for (let y = 0; y < h; y += 2) for (let x = 0; x < w; x += 2) {
      const c = px(x, y);
      if (isKey(c, 55)) continue;
      x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y);
      if (c[0] > 200 && c[2] > 160 && c[1] < 120) bleed++; // hot pink/magenta that is not part of the flat key
    }
    if (x1 < 0) problems.push('empty image');
    else {
      const margin = Math.round(w * 0.03);
      if (x0 < margin || y0 < margin || x1 > w - margin || y1 > h - margin) problems.push('subject touches/exceeds the canvas edge (needs 40px margin)');
      if (bleed > 150) problems.push(`magenta/pink inside the art (${bleed} samples): key-colour bleed`);
      if (BODY(m) && !/^(jump|fall|launch|special|ultimate|ko|intro|defeat)/.test(m.name)) {
        const feet = Math.round((y1 / h) * 1024);
        if (Math.abs(feet - 960) > 40) problems.push(`feet at y=${feet} of 1024 (want 960)`);
      }
    }
  }
  return { status: problems.length ? 'bad' : 'ok', problems, size: `${w}x${h}` };
}

const list = manifest.filter((m) => (!group || m.id.startsWith(group) || `${m.category}/${m.group}` === group || m.category === group) && (tierArg === null || m.tier === tierArg));
const groups = {};
let report = '# Raw art review (generated by tools/art/check-raw.mjs)\n\n';
for (const m of list) {
  const r = await check(m);
  const g = `${m.category}/${m.group}`;
  (groups[g] ??= { ok: 0, bad: 0, missing: 0 })[r.status]++;
  if (r.status === 'bad') report += `- [ ] \`${m.out}\`: ${r.problems.join('; ')}\n`;
  if (group && r.status !== 'ok') console.log(`${r.status.toUpperCase().padEnd(7)} ${m.id}${r.problems ? ': ' + r.problems.join('; ') : ''}`);
}
for (const [g, c] of Object.entries(groups)) console.log(`${g.padEnd(24)} ok ${String(c.ok).padStart(3)}   bad ${String(c.bad).padStart(3)}   missing ${String(c.missing).padStart(3)}`);
if (report.split('\n').length > 4) { writeFileSync(`${root}codex/REVIEW.md`, report); console.log('\nProblems written to codex/REVIEW.md'); }
